"use strict";

const CACHE_NAME = "voice-translator-v4";
const CDN_CACHE_NAME = "voice-translator-cdn-v1";
const CDN_ORIGINS = [
  "https://cdn.jsdelivr.net",
  "https://huggingface.co",
  "https://ccoreilly.github.io",
];
const PRECACHE = [
  "./",
  "./index.html",
  "./styles.css",
  "./app.js",
  "./speakers.js",
  "./speakers.worker.js",
  "./asr.js",
  "./manifest.webmanifest",
  "./icons/icon-192.png",
  "./icons/icon-512.png",
];

self.addEventListener("install", (event) => {
  event.waitUntil(
    caches
      .open(CACHE_NAME)
      .then((cache) => cache.addAll(PRECACHE))
      .then(() => self.skipWaiting())
  );
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) =>
        Promise.all(keys.filter((k) => k !== CACHE_NAME && k !== CDN_CACHE_NAME).map((k) => caches.delete(k)))
      )
      .then(() => self.clients.claim())
  );
});

self.addEventListener("fetch", (event) => {
  const request = event.request;
  const url = new URL(request.url);

  if (request.method !== "GET") return;

  if (CDN_ORIGINS.includes(url.origin)) {
    event.respondWith(
      fetch(request)
        .then((response) => {
          if (response.ok && (response.type === "cors" || response.type === "basic")) {
            const copy = response.clone();
            caches.open(CDN_CACHE_NAME).then((cache) => cache.put(request, copy));
          }
          return response;
        })
        .catch(() => caches.match(request))
    );
    return;
  }

  if (url.origin !== self.location.origin) return;

  if (request.mode === "navigate") {
    event.respondWith(
      fetch(request)
        .then((response) => {
          const copy = response.clone();
          caches.open(CACHE_NAME).then((cache) => cache.put("./index.html", copy));
          return response;
        })
        .catch(() => caches.match("./index.html"))
    );
    return;
  }

  event.respondWith(
    caches.match(request).then((cached) => {
      const network = fetch(request)
        .then((response) => {
          if (response.ok) {
            const copy = response.clone();
            caches.open(CACHE_NAME).then((cache) => cache.put(request, copy));
          }
          return response;
        })
        .catch(() => cached);
      return cached || network;
    })
  );
});
